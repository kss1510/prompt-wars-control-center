-- A signed-in user can read their own profile. Staff can read profiles for roster management.
drop policy if exists "profile read" on public.profiles;
create policy "profile read" on public.profiles for select to authenticated
using (id = (select auth.uid()) or public.is_staff());

-- No profile UPDATE policy is granted: users cannot alter their own role or email.

drop policy if exists "teams visible to signed in users" on public.teams;
create policy "teams visible to signed in users" on public.teams for select to authenticated using (true);
drop policy if exists "hosts manage teams" on public.teams;
create policy "hosts manage teams" on public.teams for all to authenticated using (public.is_host()) with check (public.is_host());

drop policy if exists "memberships visible to self or staff" on public.team_members;
create policy "memberships visible to self or staff" on public.team_members for select to authenticated
using (user_id = (select auth.uid()) or public.is_staff());
drop policy if exists "hosts manage memberships" on public.team_members;
create policy "hosts manage memberships" on public.team_members for all to authenticated
using (public.is_host()) with check (public.is_host());

drop policy if exists "read team submissions or staff" on public.submissions;
create policy "read team submissions or staff" on public.submissions for select to authenticated
using (public.is_staff() or public.is_team_member(team_id));
drop policy if exists "submit for own team or host" on public.submissions;
create policy "submit for own team or host" on public.submissions for insert to authenticated
with check (
  submitted_by = (select auth.uid())
  and (public.is_host() or public.is_team_member(team_id))
  and status = 'Submitted'
);
drop policy if exists "hosts edit submissions" on public.submissions;
create policy "hosts edit submissions" on public.submissions for update to authenticated
using (public.is_host()) with check (public.is_host());
drop policy if exists "hosts delete submissions" on public.submissions;
create policy "hosts delete submissions" on public.submissions for delete to authenticated using (public.is_host());

drop policy if exists "read scores with submission access" on public.scores;
create policy "read scores with submission access" on public.scores for select to authenticated
using (public.is_staff() or exists (
  select 1 from public.submissions s
  where s.id = submission_id and public.is_team_member(s.team_id)
));
drop policy if exists "staff insert scores" on public.scores;
create policy "staff insert scores" on public.scores for insert to authenticated
with check (public.is_staff() and scored_by = (select auth.uid()));
drop policy if exists "staff update scores" on public.scores;
create policy "staff update scores" on public.scores for update to authenticated
using (public.is_staff()) with check (public.is_staff() and scored_by = (select auth.uid()));
drop policy if exists "hosts delete scores" on public.scores;
create policy "hosts delete scores" on public.scores for delete to authenticated using (public.is_host());

