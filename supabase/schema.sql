create extension if not exists pgcrypto;

do $$ begin
  create type public.app_role as enum ('student','judge','host');
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text,
  role public.app_role not null default 'student',
  created_at timestamptz not null default now()
);

create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) between 1 and 60),
  created_at timestamptz not null default now()
);

create table if not exists public.team_members (
  team_id bigint not null references public.teams(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(team_id,user_id),
  unique(user_id) -- one team per participant
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  team_id bigint not null references public.teams(id) on delete restrict,
  round_id smallint not null check (round_id between 1 and 4),
  title text not null check (length(trim(title)) between 1 and 100),
  prompt_text text not null check (length(trim(prompt_text)) between 1 and 20000),
  output_text text not null check (length(trim(output_text)) between 1 and 30000),
  notes text check (notes is null or length(notes) <= 5000),
  status text not null default 'Submitted' check (status in ('Submitted','Scored')),
  submitted_by uuid not null default auth.uid() references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  submission_id bigint not null references public.submissions(id) on delete cascade,
  criterion_index smallint not null check (criterion_index between 0 and 3),
  points smallint not null check (points between 0 and 15),
  feedback text,
  scored_by uuid not null default auth.uid() references public.profiles(id),
  created_at timestamptz not null default now(),
  unique(submission_id,criterion_index)
);

create index if not exists submissions_team_round_idx on public.submissions(team_id,round_id);
create index if not exists submissions_created_idx on public.submissions(created_at desc);
create index if not exists scores_submission_idx on public.scores(submission_id);

-- Enforce each round's criterion count and point limits in the database (not only in React).
create or replace function public.validate_score_rubric()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  rid smallint;
  criterion_max integer;
  criterion_count integer;
begin
  select s.round_id into rid from public.submissions s where s.id = new.submission_id;
  if rid is null then raise exception 'Submission does not exist'; end if;
  criterion_count := case rid when 1 then 3 when 2 then 3 when 3 then 3 when 4 then 4 end;
  if new.criterion_index < 0 or new.criterion_index >= criterion_count then
    raise exception 'Criterion does not exist for this round';
  end if;
  criterion_max := case rid
    when 1 then (array[15,5,5])[new.criterion_index + 1]
    when 2 then (array[10,10,10])[new.criterion_index + 1]
    when 3 then (array[15,10,10])[new.criterion_index + 1]
    when 4 then (array[15,10,10,5])[new.criterion_index + 1]
  end;
  if new.points < 0 or new.points > criterion_max then
    raise exception 'Score exceeds this criterion maximum (%).', criterion_max;
  end if;
  return new;
end;
$$;
drop trigger if exists validate_score_rubric_trigger on public.scores;
create trigger validate_score_rubric_trigger before insert or update on public.scores
for each row execute procedure public.validate_score_rubric();

-- Aggregate-only views expose standings without exposing other teams' prompts or feedback.
-- View owner is the migration owner; callers receive only the columns projected here.
create or replace view public.leaderboard with (security_invoker = false) as
with per_submission as (
  select s.id, s.team_id, s.round_id,
         count(sc.id) = case s.round_id
           when 1 then 3 when 2 then 3 when 3 then 3 when 4 then 4 end as is_scored,
         coalesce(sum(sc.points),0)::integer as points
  from public.submissions s
  left join public.scores sc on sc.submission_id = s.id
  group by s.id, s.team_id, s.round_id
)
select t.id as team_id, t.name as team_name,
       coalesce(sum(ps.points) filter (where ps.is_scored),0)::integer as total_points,
       count(ps.id)::integer as submission_count,
       count(ps.id) filter (where ps.is_scored)::integer as scored_submissions
from public.teams t left join per_submission ps on ps.team_id = t.id
group by t.id, t.name;

create or replace view public.leaderboard_round_scores with (security_invoker = false) as
with per_submission as (
  select s.id, s.team_id, s.round_id,
         count(sc.id) = case s.round_id
           when 1 then 3 when 2 then 3 when 3 then 3 when 4 then 4 end as is_scored,
         coalesce(sum(sc.points),0)::integer as points
  from public.submissions s
  left join public.scores sc on sc.submission_id = s.id
  group by s.id, s.team_id, s.round_id
)
select t.id as team_id, t.name as team_name, ids.round_id,
       coalesce(sum(r.points) filter (where r.is_scored),0)::integer as points
from public.teams t cross join (select generate_series(1,4)::smallint as round_id) ids
left join per_submission r on r.team_id=t.id and r.round_id=ids.round_id
group by t.id,t.name,ids.round_id;

-- Profiles are created by the auth trigger. New accounts can never choose their own role.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, email, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name',''), new.email, 'student')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.current_role()
returns public.app_role language sql stable security definer set search_path = ''
as $$
  select p.role from public.profiles p where p.id = (select auth.uid())
$$;

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = ''
as $$
  select coalesce(public.current_role() in ('host','judge'),false)
$$;

create or replace function public.is_host()
returns boolean language sql stable security definer set search_path = ''
as $$
  select coalesce(public.current_role() = 'host',false)
$$;

create or replace function public.is_team_member(target_team bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.team_members tm
    where tm.team_id = target_team and tm.user_id = (select auth.uid())
  )
$$;

