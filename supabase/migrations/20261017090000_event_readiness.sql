create or replace function public.has_text(v text)
returns boolean language sql immutable set search_path = ''
as $$ select v is not null and length(trim(v)) > 0 $$;

-- Mirrors src/lib/rules.js (missingDeliverables). Keep both in sync.
create or replace function public.check_submission_deliverables(s public.submissions)
returns void language plpgsql stable set search_path = ''
as $$
begin
  if not public.has_text(s.title) then raise exception 'Add a submission title.'; end if;
  if not public.has_text(s.prompt_text) then raise exception 'Add the prompt(s) your team used.'; end if;
  if s.round_id in (1,2,3) and not public.has_text(s.output_text) then
    raise exception '%', case s.round_id
      when 1 then 'Round 1 requires the generated output.'
      when 2 then 'Round 2 requires the observed AI responses.'
      else 'Round 3 requires a description of what the app does and how you tested it.' end;
  end if;
  if s.round_id = 2 and not public.has_text(s.analysis_text) then
    raise exception 'Round 2 requires your analysis of whether the chatbot followed its rules.';
  end if;
  if s.round_id = 3 then
    if not public.has_text(s.artifact_filename) then
      raise exception 'Round 3 requires the HTML/project file name.';
    end if;
    if not public.has_text(s.demo_details) then
      raise exception 'Round 3 requires local demo details (laptop/seat and how to open the app).';
    end if;
  end if;
  if public.has_text(s.evidence_url) then
    if s.evidence_url !~* '^https?://' then
      raise exception 'Evidence link must start with http:// or https://.';
    end if;
    if s.evidence_url ~* '^https?://(localhost|127\.|0\.0\.0\.0|\[::1\])' then
      raise exception 'A localhost link only works on your own laptop. Put it in the local demo details instead.';
    end if;
  end if;
  if s.round_id = 4 then
    if not public.has_text(s.initial_plan) then raise exception 'Round 4 requires the initial plan.'; end if;
    if not public.has_text(s.revised_plan) then raise exception 'Round 4 requires the revised plan after the update.'; end if;
    if not public.has_text(s.risks_mitigation) then raise exception 'Round 4 requires risks and mitigation steps.'; end if;
  end if;
end;
$$;

create or replace function public.submission_fully_scored(p_submission bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select count(sc.id) = cardinality(r.criteria_max)
  from public.submissions s
  join public.rounds r on r.id = s.round_id
  left join public.scores sc on sc.submission_id = s.id
  where s.id = p_submission
  group by r.criteria_max
$$;

-- Every write path (REST, RPC, Realtime client, SQL by a signed-in user) passes through here.
-- auth.uid() is null only for trusted maintenance (SQL Editor / service role); anon has no grants.
create or replace function public.submissions_guard()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  privileged boolean := (auth.uid() is null) or public.is_host();
  staff boolean := public.is_staff();
  declared bigint;
  rname text;
begin
  select r.name into rname from public.rounds r where r.id = new.round_id;
  if rname is null then raise exception 'Unknown round %.', new.round_id; end if;

  if tg_op = 'INSERT' then
    if not privileged and not public.round_accepting(new.round_id) then
      raise exception 'Round % (%) is not open for submissions.', new.round_id, rname;
    end if;
    select p.platform_id into declared from public.team_round_platforms p
     where p.team_id = new.team_id and p.round_id = new.round_id;
    if declared is null then
      raise exception 'Select your team''s AI platform for Round % before submitting.', new.round_id;
    end if;
    if exists (select 1 from public.submissions s where s.team_id = new.team_id
               and s.round_id = new.round_id and s.status <> 'Rejected') then
      raise exception 'Your team already has a submission for Round %. Edit it instead.', new.round_id;
    end if;
    new.platform_id := declared;
    new.status := 'Submitted';
    new.demo_verified := false;
    new.demo_verified_by := null;
    new.demo_verified_at := null;
    new.reviewed_by := null;
    new.rejection_reason := null;
    new.created_at := now();
    new.updated_at := now();
    perform public.check_submission_deliverables(new);
    return new;
  end if;

  -- UPDATE
  if new.team_id <> old.team_id or new.round_id <> old.round_id
     or new.submitted_by <> old.submitted_by or new.created_at <> old.created_at then
    raise exception 'Team, round, submitter and submission time cannot be changed.';
  end if;

  if new.platform_id is distinct from old.platform_id then
    select p.platform_id into declared from public.team_round_platforms p
     where p.team_id = new.team_id and p.round_id = new.round_id;
    if new.platform_id is distinct from declared then
      raise exception 'The AI platform is changed through the round platform selection, not the submission.';
    end if;
  end if;

  if row(new.title, new.prompt_text, new.output_text, new.notes, new.analysis_text, new.evidence_text,
         new.artifact_filename, new.demo_details, new.evidence_url, new.initial_plan, new.revised_plan,
         new.risks_mitigation)
     is distinct from
     row(old.title, old.prompt_text, old.output_text, old.notes, old.analysis_text, old.evidence_text,
         old.artifact_filename, old.demo_details, old.evidence_url, old.initial_plan, old.revised_plan,
         old.risks_mitigation) then
    if staff and not privileged then
      raise exception 'Judges cannot edit a team''s work.';
    end if;
    if not privileged and (old.status <> 'Submitted' or not public.round_accepting(new.round_id)) then
      raise exception 'This submission can no longer be edited (the round closed or review has started).';
    end if;
    perform public.check_submission_deliverables(new);
  end if;

  if new.status <> old.status then
    if not staff and not privileged then
      raise exception 'Only judges and hosts can change a submission''s review status.';
    end if;
    if (new.status = 'Rejected' or old.status = 'Rejected') and not privileged then
      raise exception 'Only a host can reject or restore a submission.';
    end if;
    if new.status = 'Scored' and not coalesce(public.submission_fully_scored(new.id), false) then
      raise exception 'Score every rubric criterion before marking the submission as Scored.';
    end if;
    if old.status = 'Rejected' and exists (select 1 from public.submissions s where s.team_id = new.team_id
         and s.round_id = new.round_id and s.status <> 'Rejected' and s.id <> new.id) then
      raise exception 'This team already has another active submission for Round %.', new.round_id;
    end if;
    new.reviewed_by := coalesce(uid, old.reviewed_by);
  end if;

  if new.rejection_reason is distinct from old.rejection_reason and not privileged then
    raise exception 'Only a host can set a rejection reason.';
  end if;

  if new.demo_verified is distinct from old.demo_verified then
    if not staff and not privileged then
      raise exception 'Only judges and hosts can verify a local demo.';
    end if;
    new.demo_verified_by := case when new.demo_verified then uid end;
    new.demo_verified_at := case when new.demo_verified then now() end;
  else
    new.demo_verified_by := old.demo_verified_by;
    new.demo_verified_at := old.demo_verified_at;
  end if;

  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists submissions_guard_trigger on public.submissions;
create trigger submissions_guard_trigger before insert or update on public.submissions
for each row execute procedure public.submissions_guard();

-- Scores: criterion count and maxima come from public.rounds; rejected work cannot be scored;
-- scored_by always records the person who last changed the row.
create or replace function public.validate_score_rubric()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  maxima smallint[];
  sub_status text;
begin
  select r.criteria_max, s.status into maxima, sub_status
  from public.submissions s join public.rounds r on r.id = s.round_id
  where s.id = new.submission_id;
  if maxima is null then raise exception 'Submission does not exist'; end if;
  if sub_status = 'Rejected' then raise exception 'Rejected submissions cannot be scored.'; end if;
  if new.criterion_index < 0 or new.criterion_index >= cardinality(maxima) then
    raise exception 'Criterion does not exist for this round';
  end if;
  if new.points < 0 or new.points > maxima[new.criterion_index + 1] then
    raise exception 'Score exceeds this criterion maximum (%).', maxima[new.criterion_index + 1];
  end if;
  new.scored_by := coalesce(auth.uid(), new.scored_by);
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists validate_score_rubric_trigger on public.scores;
create trigger validate_score_rubric_trigger before insert or update on public.scores
for each row execute procedure public.validate_score_rubric();

-- Keep submission status in step with its scores.
create or replace function public.sync_submission_status()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  sid bigint := coalesce(new.submission_id, old.submission_id);
  cur text;
  complete boolean;
begin
  select s.status into cur from public.submissions s where s.id = sid;
  if cur is null or cur = 'Rejected' then return null; end if;
  complete := coalesce(public.submission_fully_scored(sid), false);
  if complete and cur <> 'Scored' then
    update public.submissions set status = 'Scored' where id = sid;
  elsif not complete and cur in ('Submitted','Scored') then
    update public.submissions set status = 'Under review' where id = sid;
  end if;
  return null;
end;
$$;
drop trigger if exists sync_submission_status_trigger on public.scores;
create trigger sync_submission_status_trigger after insert or update or delete on public.scores
for each row execute procedure public.sync_submission_status();

-- Teams and memberships: size limits, captains and freeze.
create or replace function public.teams_guard()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if auth.uid() is not null and not public.is_host() then
    raise exception 'Only a host can manage teams.';
  end if;
  if tg_op in ('INSERT','DELETE') and auth.uid() is not null
     and (select e.teams_locked from public.event_settings e) then
    raise exception 'Teams are finalized. Unlock teams before creating or deleting a team.';
  end if;
  if tg_op = 'DELETE' then return old; end if;
  if new.captain_id is not null and not exists (
       select 1 from public.team_members m where m.team_id = new.id and m.user_id = new.captain_id) then
    raise exception 'The captain must be a member of this team.';
  end if;
  return new;
end;
$$;
drop trigger if exists teams_guard_trigger on public.teams;
create trigger teams_guard_trigger before insert or update or delete on public.teams
for each row execute procedure public.teams_guard();

create or replace function public.team_members_guard()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  settings public.event_settings;
  current_size integer;
begin
  -- Authorization first, so non-hosts learn nothing about other teams from the size check.
  if auth.uid() is not null and not public.is_host() then
    raise exception 'Only a host can change team membership.';
  end if;
  select * into settings from public.event_settings;
  if auth.uid() is not null and settings.teams_locked then
    raise exception 'Teams are finalized. A host must unlock teams before changing membership.';
  end if;
  if tg_op = 'DELETE' then
    update public.teams set captain_id = null where id = old.team_id and captain_id = old.user_id;
    return old;
  end if;
  if (select p.role from public.profiles p where p.id = new.user_id) <> 'student' then
    raise exception 'Only student accounts can be team members.';
  end if;
  select count(*) into current_size from public.team_members m where m.team_id = new.team_id;
  if current_size >= settings.team_max_size then
    raise exception 'This team already has % members (maximum %).', current_size, settings.team_max_size;
  end if;
  return new;
end;
$$;
drop trigger if exists team_members_guard_trigger on public.team_members;
create trigger team_members_guard_trigger before insert or delete on public.team_members
for each row execute procedure public.team_members_guard();

