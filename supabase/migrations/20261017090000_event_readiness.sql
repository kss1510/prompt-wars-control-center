-- True while a round accepts participant submissions and platform changes.
create or replace function public.round_accepting(p_round smallint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select coalesce((select r.status = 'open' and (r.closes_at is null or now() < r.closes_at)
                   from public.rounds r where r.id = p_round), false)
$$;

-- ---------------------------------------------------------------------------
-- 3. Approved AI platforms (organizer-managed; deactivate rather than delete)
-- ---------------------------------------------------------------------------
create table if not exists public.ai_platforms (
  id bigint generated by default as identity primary key,
