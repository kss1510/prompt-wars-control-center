-- Participant (or host on a participant's behalf through host_set_round_platform).
create or replace function public.select_round_platform(p_round smallint, p_platform bigint)
returns public.team_round_platforms language plpgsql security definer set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  tid bigint;
  pname text;
  used_round smallint;
  current_platform bigint;
  result public.team_round_platforms;
begin
  if uid is null then raise exception 'Sign in first.'; end if;
  select m.team_id into tid from public.team_members m where m.user_id = uid;
  if tid is null then raise exception 'You are not assigned to a team yet. Ask the event host.'; end if;
  if not exists (select 1 from public.rounds r where r.id = p_round) then
    raise exception 'Unknown round %.', p_round;
  end if;
  if exists (select 1 from public.rounds r where r.id = p_round
             and (r.status = 'closed' or (r.closes_at is not null and now() >= r.closes_at))) then
    raise exception 'Round % is closed. Its AI platform can no longer be changed.', p_round;
  end if;
  select a.name into pname from public.ai_platforms a where a.id = p_platform and a.is_active;
  if pname is null then raise exception 'That AI platform is not on the approved list.'; end if;
  select p.round_id into used_round from public.team_round_platforms p
   where p.team_id = tid and p.platform_id = p_platform and p.round_id <> p_round;
  if used_round is not null then
    raise exception 'Your team already used % in Round %. Each round needs a different AI platform.', pname, used_round;
  end if;
  select p.platform_id into current_platform from public.team_round_platforms p
   where p.team_id = tid and p.round_id = p_round;
  if current_platform is distinct from p_platform and exists (
       select 1 from public.submissions s where s.team_id = tid and s.round_id = p_round and s.status <> 'Rejected') then
    raise exception 'Your team already submitted Round % with its current platform. Ask a host if it must be corrected.', p_round;
  end if;
  insert into public.team_round_platforms as t (team_id, round_id, platform_id, selected_by)
  values (tid, p_round, p_platform, uid)
  on conflict (team_id, round_id) do update
    set platform_id = excluded.platform_id, selected_by = excluded.selected_by, updated_at = now()
  returning * into result;
  return result;
exception when unique_violation then
  raise exception 'Your team already used % in another round. Each round needs a different AI platform.', pname;
end;
$$;

-- Host correction (any round state). p_platform null clears the declaration.
create or replace function public.host_set_round_platform(p_team bigint, p_round smallint, p_platform bigint, p_reason text)
returns void language plpgsql security definer set search_path = ''
as $$
declare used_round smallint;
begin
  if not public.is_host() then raise exception 'Only a host can correct AI platform declarations.'; end if;
  if not public.has_text(p_reason) or length(trim(p_reason)) < 3 then
    raise exception 'Give a short reason for the correction (it is recorded in the audit log).';
  end if;
  perform set_config('app.audit_reason', trim(p_reason), true);
  if p_platform is null then
    if exists (select 1 from public.submissions s where s.team_id = p_team and s.round_id = p_round) then
      raise exception 'This round has submissions linked to its platform. Choose a replacement platform instead of clearing it.';
    end if;
    delete from public.team_round_platforms where team_id = p_team and round_id = p_round;
    return;
  end if;
  if not exists (select 1 from public.ai_platforms a where a.id = p_platform) then
    raise exception 'Unknown AI platform.';
  end if;
  select p.round_id into used_round from public.team_round_platforms p
   where p.team_id = p_team and p.platform_id = p_platform and p.round_id <> p_round;
  if used_round is not null then
    raise exception 'This team already uses that platform in Round %. Change that round first.', used_round;
  end if;
  insert into public.team_round_platforms (team_id, round_id, platform_id, selected_by)
  values (p_team, p_round, p_platform, auth.uid())
  on conflict (team_id, round_id) do update
    set platform_id = excluded.platform_id, selected_by = excluded.selected_by, updated_at = now();
end;
$$;

-- Open / close / reset a round. Deadlines use the database clock.
create or replace function public.host_update_round(p_round smallint, p_status text, p_minutes integer default null)
returns public.rounds language plpgsql security definer set search_path = ''
as $$
declare result public.rounds;
begin
  if not public.is_host() then raise exception 'Only a host can open or close rounds.'; end if;
  if p_minutes is not null and (p_minutes < 1 or p_minutes > 120) then
    raise exception 'Round duration must be between 1 and 120 minutes.';
  end if;
  if p_status = 'open' then
    update public.rounds r set status = 'open', opens_at = coalesce(case when r.status = 'open' then r.opens_at end, now()),
           closes_at = now() + make_interval(mins => coalesce(p_minutes, r.duration_minutes)), updated_at = now()
     where r.id = p_round returning * into result;
  elsif p_status = 'closed' then
    update public.rounds r set status = 'closed',
           closes_at = case when r.closes_at is null or r.closes_at > now() then now() else r.closes_at end,
           updated_at = now()
     where r.id = p_round returning * into result;
  elsif p_status = 'upcoming' then
    update public.rounds r set status = 'upcoming', opens_at = null, closes_at = null,
           duration_minutes = coalesce(p_minutes, r.duration_minutes), updated_at = now()
     where r.id = p_round returning * into result;
  else
    raise exception 'Unknown round status %.', p_status;
  end if;
  if result.id is null then raise exception 'Unknown round %.', p_round; end if;
  return result;
end;
$$;

-- Finalize (lock) or unlock team membership. Locking checks every team's size.
create or replace function public.host_set_teams_locked(p_locked boolean)
returns void language plpgsql security definer set search_path = ''
as $$
declare
  settings public.event_settings;
  problems text;
begin
  if not public.is_host() then raise exception 'Only a host can finalize teams.'; end if;
  select * into settings from public.event_settings;
  if p_locked then
    if not exists (select 1 from public.teams) then raise exception 'Create teams before finalizing.'; end if;
    select string_agg(format('%s has %s', t.name, coalesce(c.n, 0)), '; ' order by t.name) into problems
    from public.teams t
    left join (select team_id, count(*) n from public.team_members group by team_id) c on c.team_id = t.id
    where coalesce(c.n, 0) not between settings.team_min_size and settings.team_max_size;
    if problems is not null then
      raise exception 'Cannot finalize: every team needs % to % members (%).',
        settings.team_min_size, settings.team_max_size, problems;
    end if;
  end if;
  update public.event_settings set teams_locked = p_locked, updated_at = now();
end;
$$;

-- Change another account's role. The first host is still bootstrapped via the SQL Editor.
create or replace function public.host_set_role(p_user uuid, p_role public.app_role)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_host() then raise exception 'Only a host can change roles.'; end if;
  if p_user = auth.uid() then raise exception 'You cannot change your own role.'; end if;
  if p_role <> 'student' and exists (select 1 from public.team_members m where m.user_id = p_user) then
    raise exception 'Remove this person from their team before making them a judge or host.';
  end if;
  update public.profiles set role = p_role where id = p_user;
  if not found then raise exception 'Unknown account.'; end if;
end;
$$;

-- Save every criterion for a submission in one transaction. Runs as the caller, so RLS applies.
create or replace function public.save_scores(p_submission bigint, p_points smallint[], p_feedback text default null)
returns integer language plpgsql security invoker set search_path = ''
as $$
declare
  maxima smallint[];
  i integer;
begin
  if not public.is_staff() then raise exception 'Only judges and hosts can enter scores.'; end if;
  select r.criteria_max into maxima from public.submissions s join public.rounds r on r.id = s.round_id
   where s.id = p_submission;
  if maxima is null then raise exception 'Submission not found.'; end if;
  if cardinality(p_points) <> cardinality(maxima) then
    raise exception 'This round needs exactly % criterion scores.', cardinality(maxima);
  end if;
  for i in 1 .. cardinality(maxima) loop
    if p_points[i] is null then raise exception 'Every criterion needs a score.'; end if;
    insert into public.scores (submission_id, criterion_index, points, feedback)
    values (p_submission, i - 1, p_points[i], nullif(trim(coalesce(p_feedback, '')), ''))
    on conflict (submission_id, criterion_index) do update
      set points = excluded.points, feedback = excluded.feedback;
  end loop;
  return (select sum(x) from unnest(p_points) x);
end;
$$;

-- A participant's own team roster (names only — no emails).
create or replace function public.my_team_roster()
returns table (team_id bigint, user_id uuid, full_name text, is_captain boolean)
language sql stable security definer set search_path = ''
as $$
  select m.team_id, m.user_id, p.full_name, t.captain_id = m.user_id
  from public.team_members m
  join public.profiles p on p.id = m.user_id
  join public.teams t on t.id = m.team_id
  where m.team_id = (select m2.team_id from public.team_members m2 where m2.user_id = auth.uid())
  order by p.full_name
$$;

-- Roster import: [{ "email": "...", "team": "...", "captain": true|false }, ...]
-- All-or-nothing. With p_apply = false it only validates and returns the report.
create or replace function public.host_import_roster(p_rows jsonb, p_apply boolean default false)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare
  settings public.event_settings;
  item jsonb;
  idx integer := 0;
  v_email text;
  v_team text;
  v_captain boolean;
  prof public.profiles;
  existing_team text;
  report jsonb := '[]'::jsonb;
  errors integer := 0;
  msg text;
  new_counts jsonb := '{}'::jsonb;
  seen text[] := '{}';
  tid bigint;
begin
  if not public.is_host() then raise exception 'Only a host can import a roster.'; end if;
  if jsonb_typeof(p_rows) <> 'array' then raise exception 'Roster must be a JSON array.'; end if;
  select * into settings from public.event_settings;
  if settings.teams_locked then raise exception 'Teams are finalized. Unlock teams before importing.'; end if;

  for item in select * from jsonb_array_elements(p_rows) loop
    idx := idx + 1;
    v_email := lower(trim(coalesce(item ->> 'email', '')));
    v_team := trim(coalesce(item ->> 'team', ''));
    v_captain := coalesce((item ->> 'captain')::boolean, false);
    msg := null;
    prof := null;
    existing_team := null;
    if v_email = '' or v_team = '' then
      msg := 'Email and team are required.';
    elsif length(v_team) > 60 then
      msg := 'Team name is longer than 60 characters.';
    elsif v_email = any(seen) then
      msg := 'Duplicate email in this file.';
    else
      seen := seen || v_email;
      select * into prof from public.profiles p where lower(p.email) = v_email;
      if prof.id is null then
        msg := 'No registered account with this email.';
      elsif prof.role <> 'student' then
        msg := 'Account is a ' || prof.role || ', not a student.';
      else
        select t.name into existing_team from public.team_members m join public.teams t on t.id = m.team_id
         where m.user_id = prof.id;
        if existing_team is not null and lower(existing_team) <> lower(v_team) then
          msg := 'Already on team ' || existing_team || '.';
        elsif existing_team is null then
          new_counts := jsonb_set(new_counts, array[lower(v_team)],
                          to_jsonb(coalesce((new_counts ->> lower(v_team))::int, 0) + 1));
        end if;
      end if;
    end if;
    if msg is not null then errors := errors + 1; end if;
    report := report || jsonb_build_object('row', idx, 'email', v_email, 'team', v_team,
                'status', case when msg is null then 'ok' else 'error' end,
                'message', coalesce(msg, case when existing_team is not null then 'Already on this team.' else 'Will be added.' end));
  end loop;

  -- Team size check across existing + incoming members.
  for v_team in select key from jsonb_each_text(new_counts) loop
    if (select count(*) from public.team_members m join public.teams t on t.id = m.team_id where lower(t.name) = v_team)
       + (new_counts ->> v_team)::int > settings.team_max_size then
      errors := errors + 1;
      report := report || jsonb_build_object('row', null, 'team', v_team, 'status', 'error',
                  'message', format('Team would exceed %s members.', settings.team_max_size));
    end if;
  end loop;

  if p_apply and errors = 0 then
    for item in select * from jsonb_array_elements(p_rows) loop
      v_email := lower(trim(item ->> 'email'));
      v_team := trim(item ->> 'team');
      select t.id into tid from public.teams t where lower(t.name) = lower(v_team);
      if tid is null then
        insert into public.teams (name) values (v_team) returning id into tid;
      end if;
      select * into prof from public.profiles p where lower(p.email) = v_email;
      insert into public.team_members (team_id, user_id) values (tid, prof.id) on conflict do nothing;
      if coalesce((item ->> 'captain')::boolean, false) then
        update public.teams set captain_id = prof.id where id = tid;
      end if;
      tid := null;
    end loop;
  end if;

  return jsonb_build_object('ok', errors = 0, 'applied', p_apply and errors = 0, 'errors', errors, 'rows', report);
end;
$$;

-- ---------------------------------------------------------------------------
-- 10. Leaderboard: only fully scored, non-rejected submissions; one per team-round.
--     Views stay SECURITY DEFINER on purpose (aggregate-only standings for all signed-in
--     users without exposing other teams' prompts). Hosts can hide standings from students.
-- ---------------------------------------------------------------------------
create or replace view public.leaderboard_round_scores with (security_invoker = false) as
with official as (
  select s.id, s.team_id, s.round_id, coalesce(sum(sc.points), 0)::integer as points
  from public.submissions s
  join public.rounds r on r.id = s.round_id
  left join public.scores sc on sc.submission_id = s.id
  where s.status = 'Scored'
  group by s.id, s.team_id, s.round_id, r.criteria_max
  having count(sc.id) = cardinality(r.criteria_max)
)
select t.id as team_id, t.name as team_name, r.id as round_id,
       coalesce(max(o.points), 0)::integer as points,
       bool_or(o.id is not null) as scored
from public.teams t
cross join public.rounds r
left join official o on o.team_id = t.id and o.round_id = r.id
where public.is_staff() or (select e.leaderboard_visible from public.event_settings e)
group by t.id, t.name, r.id;

create or replace view public.leaderboard with (security_invoker = false) as
select t.id as team_id, t.name as team_name,
       coalesce((select sum(l.points) from public.leaderboard_round_scores l where l.team_id = t.id), 0)::integer as total_points,
       (select count(*) from public.submissions s where s.team_id = t.id and s.status <> 'Rejected')::integer as submission_count,
       (select count(*) from public.leaderboard_round_scores l where l.team_id = t.id and l.scored)::integer as scored_submissions
from public.teams t
where public.is_staff() or (select e.leaderboard_visible from public.event_settings e);

