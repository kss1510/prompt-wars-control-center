-- ---------------------------------------------------------------------------
-- 4. Team ↔ round ↔ platform declaration
--    PK (team_id, round_id): one platform per team per round.
--    UNIQUE (team_id, platform_id): a team can never use the same platform twice.
--    The reservation belongs to the team-round, not to a submission, so a rejected
--    submission never strands a platform in another round.
-- ---------------------------------------------------------------------------
create table if not exists public.team_round_platforms (
  team_id bigint not null references public.teams(id) on delete cascade,
  round_id smallint not null references public.rounds(id),
  platform_id bigint not null references public.ai_platforms(id) on delete restrict,
  selected_by uuid references public.profiles(id) on delete set null,
  selected_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (team_id, round_id),
  constraint team_platform_once unique (team_id, platform_id),
  constraint team_round_platform_key unique (team_id, round_id, platform_id)
);

