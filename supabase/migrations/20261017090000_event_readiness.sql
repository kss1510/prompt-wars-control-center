-- Prompt Wars Control Center — event-readiness migration
-- Apply AFTER supabase/schema.sql (the baseline). Safe to run more than once.
--
-- Adds:
--   * event_settings (singleton): official event window, team-size limits, team freeze,
--     leaderboard visibility and the (organizer-confirmed) tie-break rule.
--   * rounds: per-round rubric maxima, duration, open/closed state and deadline.
--   * ai_platforms: organizer-managed approved AI platform list.
--   * team_round_platforms: one declared AI platform per team per round, with a
--     UNIQUE (team_id, platform_id) constraint so a team can never reuse a platform.
--   * Round-specific submission deliverables, one active submission per team per round,
--     review statuses and judge-verified local demos (Artifact Forge).
--   * Database-enforced deadlines, team-size limits, captains and team freeze.
--   * audit_log: who changed what, when, and why (hosts only).
--   * Tightened grants: anon gets nothing; authenticated gets only the columns it needs.
--
-- Nothing here drops tables or deletes rows.

begin;

-- ---------------------------------------------------------------------------
-- 1. Event settings (single row)
-- ---------------------------------------------------------------------------
create table if not exists public.event_settings (
  id boolean primary key default true check (id),
  event_name text not null default 'Prompt Wars: AI Survival Arena',
  venue text not null default 'ICT Classroom, GITAM University',
  starts_at timestamptz not null default '2026-10-23 15:00:00+05:30',
  ends_at timestamptz not null default '2026-10-23 17:00:00+05:30',
  team_min_size smallint not null default 4,
  team_max_size smallint not null default 5,
  teams_locked boolean not null default false,
  leaderboard_visible boolean not null default true,
  tie_break_rule text check (tie_break_rule is null or length(tie_break_rule) <= 500),
  updated_at timestamptz not null default now(),
  constraint event_window check (ends_at > starts_at),
  constraint team_size_range check (team_min_size >= 1 and team_min_size <= team_max_size and team_max_size <= 10)
);
insert into public.event_settings (id) values (true) on conflict (id) do nothing;

